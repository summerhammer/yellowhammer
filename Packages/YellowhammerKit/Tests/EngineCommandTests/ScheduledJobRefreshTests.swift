import Config
import Domain
@testable import EngineCommand
import Foundation
import Testing

/// Schedule Stagger Ruling item 4, issue #682: an Act regenerates its own Project's stale, idle LaunchAgents.
@Suite("An Act regenerates its own Project's stale LaunchAgents")
struct ScheduledJobRefreshTests {
    private let yhPath = "/opt/yellowhammer/yh"

    private struct Fixture: ~Copyable {
        let directory = ConfigurationDirectory()
        let home = freshHomeDirectory()
        let output = RecordingOutput()

        var agents: URL { home.appending(components: "Library", "LaunchAgents", directoryHint: .isDirectory) }

        init(stagger: Int? = 0) throws {
            try directory.writeMachineFile()
            try directory.writeValidProjectFile(id: "alpha", stagger: stagger)
            try FileManager.default.createDirectory(at: agents, withIntermediateDirectories: true)
        }

        func plistURL(_ act: Act) throws -> URL {
            agents.appending(component: "\(try label(act)).plist")
        }

        /// Installs `act`'s plist with the schedule's own firings, plus a stray one when `stale`.
        func install(_ act: Act, stale: Bool, yh: String) throws {
            var times = try Schedule(staggerMinutes: 0).firings().times(of: act)
            if stale { times.append(try #require(TimeOfDay(hour: 12, minute: 34))) }
            let job = ScheduledJob(
                projectID: try #require(ProjectID(rawValue: "alpha")), act: act, yhExecutablePath: yh,
                firings: times, pathValue: "/usr/bin:/bin"
            )
            try job.plistData(homeDirectory: home.path()).write(to: plistURL(act))
        }

        func refresh(_ control: RecordingLaunchAgentControl) -> ScheduledJobRefresh {
            let output = output
            return ScheduledJobRefresh(
                homeDirectory: home, launchAgents: control, fileExists: { _ in false }, setupTimePATH: "/usr/bin",
                output: { output.record($0) }
            )
        }

        func firings(_ act: Act) throws -> Set<TimeOfDay> {
            try #require(ScheduledJobRefresh.installedFirings(in: Data(contentsOf: plistURL(act))))
        }

        func label(_ act: Act) throws -> String {
            act.launchdLabel(projectID: try #require(ProjectID(rawValue: "alpha")))
        }
    }

    @Test("A stale idle build job is regenerated by a land Act's refresh")
    func staleIdleJobIsRegenerated() async throws {
        let fixture = try Fixture()
        for act in Act.allCases { try fixture.install(act, stale: act == .build, yh: yhPath) }
        let control = RecordingLaunchAgentControl(loadedLabels: Set(try Act.allCases.map { try fixture.label($0) }))
        let land = try #require(try RootCommand.parseAsRoot(["land", "--project", "alpha"]) as? any ActCommand)

        // The Act may stand down or throw in this bare fixture; the refresh does not depend on how it ends.
        _ = try? await land.run(configurationDirectory: fixture.directory.url, jobRefresh: fixture.refresh(control))

        let expected = Set(try Schedule(staggerMinutes: 0).firings().build)
        #expect(try fixture.firings(.build) == expected)
        let build = try fixture.label(.build)
        #expect(control.calls.contains(.bootout(build)))
        #expect(control.calls.contains(.bootstrap(build)))
        #expect(fixture.output.lines.filter { $0.contains("installed") }.count == 1)
        // The installed executable path is kept, never repointed.
        #expect(ScheduledExecutable.installedPath(at: try fixture.plistURL(.build)) == yhPath)
    }

    @Test("The running job is skipped and left byte-identical")
    func runningJobIsSkipped() async throws {
        let fixture = try Fixture()
        try fixture.install(.land, stale: true, yh: yhPath)
        let before = try Data(contentsOf: fixture.plistURL(.land))
        let land = try fixture.label(.land)
        let control = RecordingLaunchAgentControl(
            loadedLabels: [land], states: [land: [.running, .running, .running, .running]]
        )

        await fixture.refresh(control).refreshAfterResolving("alpha", configurationDirectory: fixture.directory.url)

        #expect(try Data(contentsOf: fixture.plistURL(.land)) == before)
        #expect(!control.calls.contains(.bootout(land)))
        #expect(fixture.output.lines.contains { $0.contains("skipped running") })
    }

    @Test("An unloaded job is rewritten and never loaded")
    func unloadedJobStaysUnloaded() async throws {
        let fixture = try Fixture()
        try fixture.install(.build, stale: true, yh: yhPath)
        let control = RecordingLaunchAgentControl()

        await fixture.refresh(control).refreshAfterResolving("alpha", configurationDirectory: fixture.directory.url)

        #expect(try fixture.firings(.build) == Set(try Schedule(staggerMinutes: 0).firings().build))
        #expect(control.calls.isEmpty)
    }

    @Test("A matching job is untouched, with no bootout or bootstrap and no output")
    func matchingJobIsUntouched() async throws {
        let fixture = try Fixture()
        for act in Act.allCases { try fixture.install(act, stale: false, yh: yhPath) }
        let before = try Act.allCases.map { try Data(contentsOf: fixture.plistURL($0)) }
        let control = RecordingLaunchAgentControl(loadedLabels: Set(try Act.allCases.map { try fixture.label($0) }))

        await fixture.refresh(control).refreshAfterResolving("alpha", configurationDirectory: fixture.directory.url)

        #expect(try Act.allCases.map { try Data(contentsOf: fixture.plistURL($0)) } == before)
        #expect(control.calls.isEmpty)
        #expect(fixture.output.lines.isEmpty)
    }

    @Test("A Project that records no stagger_minutes is untouched")
    func unrecordedOffsetIsUntouched() async throws {
        let fixture = try Fixture(stagger: nil)
        try fixture.install(.build, stale: true, yh: yhPath)
        let before = try Data(contentsOf: fixture.plistURL(.build))
        let control = RecordingLaunchAgentControl(loadedLabels: [try fixture.label(.build)])

        await fixture.refresh(control).refreshAfterResolving("alpha", configurationDirectory: fixture.directory.url)

        #expect(try Data(contentsOf: fixture.plistURL(.build)) == before)
        #expect(control.calls.isEmpty)
    }

    @Test("A rehearsal Act never touches LaunchAgents")
    func rehearsalDoesNothing() async throws {
        let fixture = try Fixture()
        try fixture.install(.build, stale: true, yh: yhPath)
        let before = try Data(contentsOf: fixture.plistURL(.build))
        let control = RecordingLaunchAgentControl(loadedLabels: [try fixture.label(.build)])
        let land = try #require(
            try RootCommand.parseAsRoot(["land", "--project", "alpha", "--rehearsal"]) as? any ActCommand
        )

        _ = try? await land.run(configurationDirectory: fixture.directory.url, jobRefresh: fixture.refresh(control))

        #expect(try Data(contentsOf: fixture.plistURL(.build)) == before)
        #expect(control.calls.isEmpty)
    }

    @Test("A refresh failure is output, not a failure")
    func refreshFailureDoesNotThrow() async throws {
        let fixture = try Fixture()
        try fixture.install(.build, stale: true, yh: yhPath)
        let build = try fixture.label(.build)
        let control = RecordingLaunchAgentControl(loadedLabels: [build], inspectionFailures: [build])

        await fixture.refresh(control).refreshAfterResolving("alpha", configurationDirectory: fixture.directory.url)

        #expect(fixture.output.lines.contains { $0.contains("could not load") && $0.contains(build) })
    }
}

private extension Schedule.ScheduledFirings {
    func times(of act: Act) -> [TimeOfDay] {
        switch act {
        case .author: author
        case .build: build
        case .land: land
        }
    }
}
